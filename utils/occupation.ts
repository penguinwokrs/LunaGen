/**
 * 職業の表示名を解決する。
 *
 * 優先順位は「APIが表を返してきたらそれを使う > 手元の表 > 元の値が文字列ならそのまま」。
 * 解決できなければ null を返す（コード番号をそのまま出さない。「職業: 20」は情報ではない）。
 *
 * @param value `occupation` の値（数値コード、または表示名の文字列）
 * @param listFromApi APIレスポンスに `occupation_list` があればそれ
 */
export function resolveOccupation(
    value: unknown,
    listFromApi?: Record<string, string>
): string | null {
    if (value === undefined || value === null || value === "") return null

    const key = String(value)
    const fromApi = listFromApi?.[key]
    if (fromApi) return fromApi

    const known = OCCUPATION_LABELS[key]
    if (known) return known

    // 数値コードなのに表に無い＝サイト側で項目が増えた可能性。
    // 番号をそのまま出しても意味が無いので出さない。
    if (/^\d+$/.test(key)) return null

    const text = key.trim()
    return text.length > 0 ? text : null
}
